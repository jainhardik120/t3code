#!/usr/bin/env bash
# Reclaim disk space from the source tree once the standalone release is live.
#
#   ./infra/self-hosted/cleanup.sh --dry-run   # show what would go, delete nothing
#   ./infra/self-hosted/cleanup.sh             # node_modules, dist, caches
#   ./infra/self-hosted/cleanup.sh --all       # + mobile prebuild, pnpm store, git gc
#
# Safe only because the service runs from an immutable release directory, not
# from this checkout — the script refuses to delete anything until it has proved
# that is still true and that the live release is healthy.
set -euo pipefail

# shellcheck source=common.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/common.sh"

DRY_RUN=0
DO_MOBILE=0
DO_STORE=0
DO_GIT_GC=0

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run | -n) DRY_RUN=1 ;;
    --mobile) DO_MOBILE=1 ;;
    --store) DO_STORE=1 ;;
    --git-gc) DO_GIT_GC=1 ;;
    --all) DO_MOBILE=1; DO_STORE=1; DO_GIT_GC=1 ;;
    *) echo "unknown flag: $1" >&2; exit 2 ;;
  esac
  shift
done

cd "$REPO_ROOT"

# --- safety gates ----------------------------------------------------------
#
# Every check here answers one question: can the running server survive losing
# this checkout? Before install-service.sh the answer was no — the unit ran
# apps/server/dist/bin.mjs and resolved effect, node-pty and the web client out
# of the repo. Do not weaken these.

say "Verifying the running service does not depend on this checkout"

live="$(current_release)"
[ -n "$live" ] || die "no live release at $CURRENT_LINK — the repo may still be the only copy"
release_is_complete "$live" || die "live release $live is incomplete — refusing to clean"
assert_unit_uses_symlink

systemctl --user is-active --quiet "$SERVICE" || die "$SERVICE is not running — start it before cleaning"

exec_start="$(systemctl --user show "$SERVICE" -p ExecStart --value 2>/dev/null || true)"
case "$exec_start" in
  *"$REPO_ROOT"*) die "the unit still references $REPO_ROOT — run install-service.sh and release.sh first" ;;
esac

main_pid="$(systemctl --user show "$SERVICE" -p MainPID --value 2>/dev/null || echo 0)"
if [ "${main_pid:-0}" -gt 0 ] && [ -r "/proc/$main_pid/cmdline" ]; then
  if tr '\0' ' ' < "/proc/$main_pid/cmdline" | grep -q "$REPO_ROOT"; then
    die "the running process still has $REPO_ROOT on its command line — restart it onto the release first"
  fi
fi

curl -fsS -o /dev/null --max-time 5 "$HEALTH_URL" || die "$HEALTH_URL is not answering — fix the service before cleaning"

echo "live release: $(basename "$live")"
echo "service:      healthy, running outside the repo"

if [ -n "$(git ls-files -u 2>/dev/null)" ]; then
  die "this checkout has an unfinished merge — resolve it before cleaning"
fi

# --- collect targets -------------------------------------------------------

targets=()
# Must return 0 even when the path is absent, or `set -e` ends the script
# on the first optional target that happens not to exist.
add_target() {
  [ -e "$1" ] && targets+=("$1")
  return 0
}

# Dependency trees. Every one of these is reproduced by `pnpm install`.
while IFS= read -r d; do add_target "$d"; done < <(
  find "$REPO_ROOT" -maxdepth 4 -type d -name node_modules -prune 2>/dev/null
)

# Build outputs and task caches.
while IFS= read -r d; do add_target "$d"; done < <(
  find "$REPO_ROOT" -maxdepth 3 -type d \( -name dist -o -name dist-electron -o -name .vite-plus \) \
    -not -path "*/node_modules/*" -prune 2>/dev/null
)
add_target "$REPO_ROOT/native/resource-monitor/target"   # cargo

# Deliberately NOT cleaned: .repos looks like a cache of synced reference repos,
# but its ~13k files are tracked in git. Deleting it leaves the worktree full of
# pending deletions, which then blocks sync-upstream.sh's clean-tree check and
# invites committing them by accident. Recover with `git checkout -- .repos`.

if [ "$DO_MOBILE" -eq 1 ]; then
  add_target "$REPO_ROOT/apps/mobile/android"
  add_target "$REPO_ROOT/apps/mobile/ios"
fi

# Never delete anything git is tracking. Generated directories are ignored by
# definition, so a tracked file inside a target means the target was misjudged —
# removing it would leave pending deletions that block the next sync and could be
# committed by accident.
kept=()
for t in "${targets[@]}"; do
  if [ -n "$(git ls-files -- "$t" | head -1)" ]; then
    warn "skipping ${t#"$REPO_ROOT"/} — it contains git-tracked files"
    continue
  fi
  kept+=("$t")
done
targets=("${kept[@]}")

[ "${#targets[@]}" -gt 0 ] || { say "Nothing to clean"; exit 0; }

say "Targets"
for t in "${targets[@]}"; do
  printf '%8s  %s\n' "$(du -sh "$t" 2>/dev/null | cut -f1)" "${t#"$REPO_ROOT"/}"
done

# --- the keystore ----------------------------------------------------------
#
# apps/mobile/android is gitignored and regenerated by `expo prebuild`, but the
# debug keystore inside it is NOT reproducible: prebuild mints a fresh random
# key. Since the installed APK is signed with this one, losing it means the next
# build cannot upgrade over the installed app — Android rejects a signature
# change, so the user has to uninstall first and loses app data and pairing.

keystore="$REPO_ROOT/apps/mobile/android/app/debug.keystore"
keystore_backup="$DEPLOY_ROOT/mobile/debug.keystore"
if [ "$DO_MOBILE" -eq 1 ] && [ -f "$keystore" ]; then
  say "Backing up the Android debug keystore (not reproducible by prebuild)"
  mkdir -p "$(dirname "$keystore_backup")"
  if [ "$DRY_RUN" -eq 0 ]; then
    cp -f "$keystore" "$keystore_backup"
    echo "saved: $keystore_backup"
  else
    echo "would save: $keystore_backup"
  fi
fi

before_free="$(df -h --output=avail "$HOME" | tail -1 | tr -d ' ')"

if [ "$DRY_RUN" -eq 1 ]; then
  cat <<EOF

Dry run — nothing deleted. Free space now: $before_free

Note: node_modules files are hardlinked into the pnpm store, so removing them
frees much less than the sizes above suggest. Add --store to prune the store,
which is what actually returns those bytes.
EOF
  exit 0
fi

# --- delete ----------------------------------------------------------------

say "Deleting"
for t in "${targets[@]}"; do
  echo "  ${t#"$REPO_ROOT"/}"
  rm -rf "$t"
done

if [ "$DO_STORE" -eq 1 ]; then
  # The store is shared with every other pnpm project on this machine. Prune
  # only drops packages nothing references any more, so other checkouts keep
  # theirs; the cost is re-downloading ours on the next install.
  say "Pruning the pnpm store (shared with other projects on this machine)"
  pnpm store prune || warn "pnpm store prune failed — continuing"
fi

if [ "$DO_GIT_GC" -eq 1 ]; then
  say "Repacking git objects"
  git gc --prune=now --quiet || warn "git gc failed — continuing"
fi

after_free="$(df -h --output=avail "$HOME" | tail -1 | tr -d ' ')"

cat <<EOF

$(say "Done")
free space: $before_free -> $after_free
repo size:  $(du -sh "$REPO_ROOT" 2>/dev/null | cut -f1)

The service is untouched and still serving from $(basename "$live").

To work in this checkout again:

    pnpm install                      # restores node_modules
    pnpm sync:repos                   # restores .repos, only if you need it

release.sh already runs pnpm install as its first step, so the next upgrade
works from a cleaned tree with no extra action.
EOF

if [ "$DO_MOBILE" -eq 1 ]; then
  cat <<EOF

Mobile: apps/mobile/android is gone. Regenerate it with
    APP_VARIANT=production T3CODE_DISABLE_UPDATES=1 EXPO_NO_GIT_STATUS=1 npx expo prebuild --clean --platform android
then RESTORE THE KEYSTORE before building:
    cp $keystore_backup apps/mobile/android/app/debug.keystore
Building without it produces an APK Android refuses to install over the current
one, and reinstalling clears the app's data and pairing.
EOF
fi
